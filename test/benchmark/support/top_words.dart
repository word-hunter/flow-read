UserVocabularyService createFakeVocabForProfile(String profile) {
  final random = Random(42);
  final candidates = _loadTopWords();

  return switch (profile) {
    'empty' => createFakeVocab(knownWords: {}),
    'light' => createFakeVocab(knownWords: _sample(candidates, 1000, random)),
    'medium' => createFakeVocab(knownWords: _sample(candidates, 5000, random)),
    'heavy' => createFakeVocab(knownWords: _sample(candidates, 10000, random)),
    'extreme' => createFakeVocab(knownWords: _sample(candidates, 30000, random)),
    _ => throw ArgumentError('Unknown vocabulary profile: $profile'),
  };
}

const List<String> vocabularyProfiles = [
  'empty',
  'light',
  'medium',
  'heavy',
];

Set<String> _sample(List<String> candidates, int count, Random random) {
  final result = <String>{};
  final shuffled = List<String>.from(candidates)..shuffle(random);
  for (var i = 0; i < count && i < shuffled.length; i++) {
    result.add(shuffled[i]);
  }
  return result;
}

List<String> _loadTopWords() {
  final words = <String>{};
  for (final base in _baseWords) {
    words.add(base);
    if (base.length >= 4) {
      words.add('${base}ing');
      words.add('${base}ed');
      words.add('${base}er');
      words.add('${base}ly');
      words.add('re$base');
      words.add('un$base');
      words.add('mis$base');
      words.add('over$base');
      words.add('${base}ment');
      words.add('${base}tion');
      words.add('${base}ness');
      words.add('${base}ful');
      words.add('${base}less');
      words.add('${base}able');
      words.add('${base}ous');
      words.add('${base}ive');
      words.add('${base}al');
      words.add('${base}ize');
      words.add('dis$base');
      words.add('pre$base');
    }
  }
  return words.toList();
}

